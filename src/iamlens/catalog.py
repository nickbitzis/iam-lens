def access_level(action: str) -> str:
    if action in PERMISSIONS_MANAGEMENT:
        return "permissions"
    verb = action.split(":", 1)[1]
    for prefix, level in (
        ("Get", "read"),
        ("Describe", "read"),
        ("Lookup", "read"),
        ("BatchGet", "read"),
        ("Query", "read"),
        ("Scan", "read"),
        ("Receive", "read"),
        ("Filter", "read"),
        ("List", "list"),
    ):
        if verb.startswith(prefix):
            return level
    return "write"


@lru_cache(maxsize=4096)
def expand(pattern: str) -> tuple[str, ...]:
    """Catalog actions matched by one pattern."""
    return tuple(a for a in ALL_ACTIONS if action_match(pattern, a))


